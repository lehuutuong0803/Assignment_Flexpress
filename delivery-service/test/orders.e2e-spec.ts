import { randomUUID } from 'node:crypto';
import { INestApplication } from '@nestjs/common';
import { Test } from '@nestjs/testing';
import request from 'supertest';
import { App } from 'supertest/types';
import { DataSource } from 'typeorm';
import { AppModule } from '../src/app.module';
import { configureApp } from '../src/app.setup';
import { TokenVerifier } from '../src/auth/token-verifier';
import {
  COMPANY_A,
  COMPANY_B,
  createTestKeys,
  TEST_AUDIENCE,
  TEST_ISSUER,
} from './support/tokens';

/**
 * Boots the whole app against a real PostgreSQL (docker compose locally, a service container in
 * CI). Only token verification is swapped: tokens are signed with keys generated by the test, so
 * Keycloak isn't needed. Everything else (guards, validation, scoping, SQL) is production code.
 */
describe('Orders API (e2e)', () => {
  let app: INestApplication<App>;
  const users = {
    dispatcherA: { sub: randomUUID(), company: COMPANY_A, role: 'dispatcher' },
    driverA: { sub: randomUUID(), company: COMPANY_A, role: 'driver' },
    dispatcherB: { sub: randomUUID(), company: COMPANY_B, role: 'dispatcher' },
  };
  const tokens: Record<keyof typeof users, string> = {
    dispatcherA: '',
    driverA: '',
    dispatcherB: '',
  };

  beforeAll(async () => {
    const keys = await createTestKeys();
    for (const name of Object.keys(users) as (keyof typeof users)[]) {
      const u = users[name];
      tokens[name] = await keys.sign({
        sub: u.sub,
        company_id: u.company,
        realm_access: { roles: [u.role] },
      });
    }

    const moduleRef = await Test.createTestingModule({ imports: [AppModule] })
      .overrideProvider(TokenVerifier)
      .useValue(
        new TokenVerifier(keys.jwks, {
          issuer: TEST_ISSUER,
          audience: TEST_AUDIENCE,
        }),
      )
      .compile();
    app = moduleRef.createNestApplication();
    configureApp(app);
    await app.init();
    await app.get(DataSource).runMigrations();
  });

  afterAll(async () => {
    await app?.close();
  });

  const api = () => request(app.getHttpServer());
  const createOrder = () =>
    api()
      .post('/orders')
      .auth(tokens.dispatcherA, { type: 'bearer' })
      .send({ pickupAddress: 'Warehouse 1', deliveryAddress: 'Customer 9' })
      .expect(201);

  it('serves liveness and readiness without a token', async () => {
    await api().get('/health').expect(200);
    const { body } = await api().get('/health/ready').expect(200);
    expect(body.info.database.status).toBe('up');
  });

  it('exposes Prometheus metrics with route templates, not raw ids', async () => {
    await api().get('/orders').expect(401);
    await api()
      .get(`/orders/${randomUUID()}`)
      .auth(tokens.dispatcherA, { type: 'bearer' })
      .expect(404);
    const { text, headers } = await api().get('/metrics').expect(200);
    expect(headers['content-type']).toContain('text/plain');
    expect(text).toMatch(
      /http_requests_total\{method="GET",route="\/orders",status_code="401"\} \d+/,
    );
    expect(text).toContain('route="/orders/:id",status_code="404"');
    expect(text).toContain('http_request_duration_seconds_bucket');
    expect(text).not.toContain('route="/metrics"');
  });

  it('rejects a request without a token (401)', async () => {
    await api().get('/orders').expect(401);
  });

  it('rejects a forged token (401)', async () => {
    const forged = await (
      await createTestKeys()
    ).sign({ sub: users.dispatcherA.sub });
    await api().get('/orders').auth(forged, { type: 'bearer' }).expect(401);
  });

  it('lets a dispatcher create and read an order of their company', async () => {
    const { body: created } = await createOrder();
    expect(created).toMatchObject({
      status: 'CREATED',
      companyId: COMPANY_A,
      createdBy: users.dispatcherA.sub,
    });
    await api()
      .get(`/orders/${created.id}`)
      .auth(tokens.dispatcherA, { type: 'bearer' })
      .expect(200);
  });

  it('hides an order from another company (404, not 403)', async () => {
    const { body: created } = await createOrder();
    await api()
      .get(`/orders/${created.id}`)
      .auth(tokens.dispatcherB, { type: 'bearer' })
      .expect(404);
    const { body: list } = await api()
      .get('/orders?limit=100')
      .auth(tokens.dispatcherB, { type: 'bearer' })
      .expect(200);
    expect(list.items.map((o: { id: string }) => o.id)).not.toContain(
      created.id,
    );
  });

  it('ignores companyId in the body: it is rejected (400)', async () => {
    await api()
      .post('/orders')
      .auth(tokens.dispatcherA, { type: 'bearer' })
      .send({ pickupAddress: 'a', deliveryAddress: 'b', companyId: COMPANY_B })
      .expect(400);
  });

  it('forbids a driver from creating orders (403)', async () => {
    await api()
      .post('/orders')
      .auth(tokens.driverA, { type: 'bearer' })
      .send({ pickupAddress: 'a', deliveryAddress: 'b' })
      .expect(403);
  });

  it('applies a retried status change only once (idempotency)', async () => {
    const { body: order } = await createOrder();
    await api()
      .post(`/orders/${order.id}/assign`)
      .auth(tokens.dispatcherA, { type: 'bearer' })
      .send({ driverId: users.driverA.sub })
      .expect(200);

    const key = randomUUID();
    const change = () =>
      api()
        .post(`/orders/${order.id}/status`)
        .auth(tokens.driverA, { type: 'bearer' })
        .set('Idempotency-Key', key)
        .send({ status: 'PICKED_UP', lat: 52.52, lng: 13.4 });

    const first = await change().expect(200);
    const retry = await change().expect(200);
    expect(retry.headers['idempotent-replayed']).toBe('true');
    expect(retry.body).toEqual(first.body);

    const { body: events } = await api()
      .get(`/orders/${order.id}/events`)
      .auth(tokens.dispatcherA, { type: 'bearer' })
      .expect(200);
    expect(events.map((e: { toStatus: string }) => e.toStatus)).toEqual([
      'ASSIGNED',
      'PICKED_UP',
    ]);

    await api()
      .post(`/orders/${order.id}/status`)
      .auth(tokens.driverA, { type: 'bearer' })
      .set('Idempotency-Key', key)
      .send({ status: 'IN_TRANSIT' })
      .expect(422);
  });

  it('rejects an invalid transition with the documented 409 body', async () => {
    const { body: order } = await createOrder();
    await api()
      .post(`/orders/${order.id}/assign`)
      .auth(tokens.dispatcherA, { type: 'bearer' })
      .send({ driverId: users.driverA.sub })
      .expect(200);
    const { body } = await api()
      .post(`/orders/${order.id}/status`)
      .auth(tokens.driverA, { type: 'bearer' })
      .set('Idempotency-Key', randomUUID())
      .send({ status: 'DELIVERED' })
      .expect(409);
    expect(body).toEqual({
      error: 'INVALID_TRANSITION',
      message:
        'Cannot change status from ASSIGNED to DELIVERED. Allowed: PICKED_UP',
    });
  });
});
